var legacySoundEventByName = func() map[string]uint32 {
	m := make(map[string]uint32, len(legacySoundEventByID))
	for id, name := range legacySoundEventByID {
		m[name] = id
	}
	return m
}()

func legacySoundType(io protocol.IO, soundType *string) {
	if proto.IsReader(io) {
		var id uint32
		io.Varuint32(&id)
		name, ok := legacySoundEventByID[id]
		if !ok {
			io.UnknownEnumOption(id, "legacy level sound event type")
			return
		}
		*soundType = name
		return
	}

	id, ok := legacySoundEventByName[*soundType]
	if !ok {
		io.UnknownEnumOption(*soundType, "legacy level sound event type")
		return
	}
	io.Varuint32(&id)
}
